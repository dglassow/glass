  /** Pull each connected agent's session list into `remote` (minus ones we hold),
   *  so a viewer sees shells opened by OTHER devices, not just its own. */
  async function refreshRemoteSessions(): Promise<void> {
    const agents = latestDevices.filter((d) => d.roles.includes("agent") && d.state === "connected");
    await Promise.all(
      agents.map(async (a) => {
        let list: Awaited<ReturnType<typeof client.listSessions>>;
        try {
          list = await client.listSessions(a.id);
        } catch {
          return;
        }
        for (const [sid, r] of remote) if (r.agentId === a.id) remote.delete(sid);
        for (const s of list) {
          if (!s.alive) continue; // already exited — nothing to attach to
          if (workspace.has(s.id)) continue; // already attached locally
          remote.set(s.id, { agentId: a.id, title: s.title });
        }
      }),
    );
  }

  /** Plan §6: open one shell on connect ONLY if the fleet has nothing to show. */
  function maybeAutoOpen(): void {
    if (didAutoOpen || workspace.sessionList().length > 0 || remote.size > 0) return;
    const agent = latestDevices.find((d) => d.roles.includes("agent") && d.state === "connected");
    if (agent) {
      didAutoOpen = true;
      void openShell(agent.id, agent.name);
    }
  }

  async function openShell(agentId: string, agentName: string): Promise<void> {
    try {
      const n = workspace.sessionList().filter((s) => s.agentId === agentId).length + 1;
      const session = await client.createSession(agentId, { kind: "pty" });
      remote.delete(session.id); // in case its own broadcast raced ahead of us
      workspace.add(session.id, agentId, `${agentName} · shell ${n}`);
      workspace.show(session.id); // switch to the new shell
      app.classList.remove("drawer-open"); // mobile: reveal the new shell
      renderSidebar();
    } catch (err) {
      statusText.textContent = `could not open shell: ${String(err)}`;
    }
  }

  /**
   * Plan §7: browse locally, egress elsewhere. Ask THIS Mac's agent for a
   * loopback SOCKS forwarder aimed at the chosen egress device, then launch an
   * isolated browser profile (one per egress device — cookie jars never cross
   * egress identities) pinned to it. Desktop only: needs the local agent and
   * the shell's launch command.
   */
  async function browseVia(egressId: string, egressName: string): Promise<void> {
    const local = extras?.localAgentId;
    if (!local) return;
    try {
      statusText.textContent = `starting proxy via ${egressName}…`;
      const port = await client.openProxyForward(local, egressId);
      await launchProxiedBrowser({ socksHost: "127.0.0.1", socksPort: port, profileName: `egress-${egressId}` });
      statusText.textContent = `browser launched — egress via ${egressName}`;
    } catch (err) {
      statusText.textContent = `browse via ${egressName} failed: ${err instanceof Error ? err.message : String(err)}`;
    }
  }

  /** Attach a session that lives on another device and bring it into the workspace. */
  async function openRemote(agentId: string, sessionId: string, title: string): Promise<void> {
    remote.delete(sessionId);
    workspace.add(sessionId, agentId, title);
    workspace.show(sessionId);
    app.classList.remove("drawer-open");
    renderSidebar();
    try {
      await client.attach(agentId, sessionId); // scrollback paints via onScrollback
    } catch (err) {
      workspace.markDead(sessionId, "could not attach");
      statusText.textContent = `could not attach: ${String(err)}`;
    }
  }

  /** After a successful session.rename, sync our local copies of the title.
   *  (Other viewers sync via the session.renamed broadcast.) */
  function applySessionRename(s: { id: string; title: string }): void {
    workspace.rename(s.id, s.title);
    const r = remote.get(s.id);
    if (r) r.title = s.title;
    renderSidebar();
  }

  /**
   * Right-click a sidebar row (session or device): swap its name for an inline
   * input. Enter or clicking away commits via `commit` (the rename rides the
   * protocol, so every device's sidebar updates from the broadcast); Esc
   * cancels; failures land in the status line.
   */
  function attachRenamer(item: HTMLElement, stitle: HTMLElement, commit: (name: string) => Promise<void>): void {
    item.addEventListener("contextmenu", (e) => {
      e.preventDefault();
      if (item.querySelector("input")) return; // already editing
      const input = document.createElement("input");
      input.className = "session-rename";
      input.value = stitle.textContent ?? "";
      input.maxLength = 80;
      let done = false;
      const finish = (commitIt: boolean): void => {
        if (done) return;
        done = true;
        const title = input.value.trim();
        input.replaceWith(stitle);
        if (commitIt && title && title !== stitle.textContent) {
          void commit(title).catch(
            (err) => (statusText.textContent = `rename failed: ${err instanceof Error ? err.message : String(err)}`),
          );
        }
      };
      input.addEventListener("keydown", (ke) => {
        ke.stopPropagation();
        if (ke.key === "Enter") finish(true);
        else if (ke.key === "Escape") finish(false);
      });
      input.addEventListener("blur", () => finish(true));
      // Editing must not trigger the row's own click/drag behaviour.
      input.addEventListener("click", (ce) => ce.stopPropagation());
      input.addEventListener("mousedown", (ce) => ce.stopPropagation());
      stitle.replaceWith(input);
      input.focus();
      input.select();
    });
  }

  /** Sidebar: each agent (device) with its sessions nested beneath it. */
  function renderSidebar(): void {
    syncMessagesWidget();
    deviceList.replaceChildren();
    const agents = latestDevices.filter((d) => d.roles.includes("agent"));
    const sessions = workspace.sessionList();
    const remoteList = [...remote.entries()]
      .filter(([sid]) => !workspace.has(sid))
      .map(([sid, r]) => ({ sessionId: sid, agentId: r.agentId, title: r.title }));
    const agentIds = [...new Set([...agents.map((a) => a.id), ...sessions.map((s) => s.agentId), ...remoteList.map((s) => s.agentId)])];
    if (agentIds.length === 0) {
      const empty = document.createElement("div");
      empty.className = "empty";
      empty.textContent = "no agents online";
      deviceList.append(empty);
      return;
    }
    for (const agentId of agentIds) {
      const agent = agents.find((a) => a.id === agentId);
      const connected = agent?.state === "connected";

      const row = document.createElement("div");
      row.className = "device";
      row.dataset["state"] = agent?.state ?? "offline";
      const dot = document.createElement("span");
      dot.className = "dot";
      dot.title = agent?.state ?? "offline";
      const name = document.createElement("span");
      name.className = "device-name";
      name.textContent = agent?.name ?? agentId;
      // Right-click renames the DEVICE (hub/spoke) fleet-wide; only meaningful
      // for devices the hub currently knows (they're the only ones rendered
      // with a live record anyway).
      if (agent) {
        row.title = "right-click to rename this device";
        attachRenamer(row, name, (t) => client.renameDevice(agentId, t).then(() => refreshDevices()));
      }
      const newShell = document.createElement("button");
      newShell.textContent = "+ shell";
      newShell.disabled = !connected;
      newShell.addEventListener("click", () => void openShell(agentId, agent?.name ?? agentId));
      row.append(dot, name);
      // Browse-via-device (plan §7) — desktop only: needs this Mac's agent for
      // the SOCKS forwarder and the shell to launch the isolated profile.
      if (isNative() && extras?.localAgentId) {
        const browse = document.createElement("button");
        browse.className = "device-browse";
        browse.textContent = "🌐";
        browse.disabled = !connected;
        browse.title = `browse the web with “${agent?.name ?? agentId}” as egress (isolated profile)`;
        browse.addEventListener("click", () => void browseVia(agentId, agent?.name ?? agentId));
        row.append(browse);
      }
      row.append(newShell);
      deviceList.append(row);

      for (const s of sessions.filter((x) => x.agentId === agentId)) {
        const item = document.createElement("div");
        item.className = "session";
        item.draggable = true;
        item.dataset["visible"] = String(s.visible);
        item.dataset["focused"] = String(s.focused);
        const stitle = document.createElement("span");
        stitle.className = "session-title";
        stitle.textContent = s.title.replace(/^.*·\s*/, ""); // "shell N" (device shown above)
        const kill = document.createElement("button");
        kill.className = "session-kill";
        kill.textContent = "×";
        kill.title = "end this session";
        kill.addEventListener("click", (e) => {
          e.stopPropagation();
          client.closeSession(agentId, s.sessionId);
          workspace.kill(s.sessionId);
        });
        item.append(stitle, kill);
        item.title = "right-click to rename";
        attachRenamer(item, stitle, (t) => client.renameSession(agentId, s.sessionId, t).then(applySessionRename));
        item.addEventListener("click", () => {
          workspace.show(s.sessionId);
          app.classList.remove("drawer-open"); // mobile: close the drawer
        });
        item.addEventListener("dragstart", (e) => {
          e.dataTransfer?.setData(SESSION_MIME, s.sessionId);
          if (e.dataTransfer) e.dataTransfer.effectAllowed = "move";
        });
        deviceList.append(item);
      }

      // Sessions on this agent that we haven't attached yet (opened by another
      // device). Click to attach + view; × ends it remotely.
      for (const s of remoteList.filter((x) => x.agentId === agentId)) {
        const item = document.createElement("div");
        item.className = "session";
        item.dataset["remote"] = "true";
        item.dataset["visible"] = "false";
        const stitle = document.createElement("span");
        stitle.className = "session-title";
        stitle.textContent = s.title.replace(/^.*·\s*/, "") || "shell";
        const hint = document.createElement("span");
        hint.className = "session-hint";
        hint.textContent = "open";
        const kill = document.createElement("button");
        kill.className = "session-kill";
        kill.textContent = "×";
        kill.title = "end this session";
        kill.addEventListener("click", (e) => {
          e.stopPropagation();
          client.closeSession(agentId, s.sessionId);
          remote.delete(s.sessionId);
          renderSidebar();
        });
        item.append(stitle, hint, kill);
        item.title = "right-click to rename";
        attachRenamer(item, stitle, (t) => client.renameSession(agentId, s.sessionId, t).then(applySessionRename));
        item.addEventListener("click", () => void openRemote(agentId, s.sessionId, s.title));
        deviceList.append(item);
      }
    }
  }

