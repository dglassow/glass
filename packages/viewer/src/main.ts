/**
 * Desktop Viewer entry — session-list sidebar + tiling terminal panes over the
 * Hub (plan §6). This is the desktop capability tier; the PWA tier is chat-only
 * and lands in Phase 5.
 *
 * FIRST-RUN FLOW: instead of a bare hub-URL form, the viewer opens with a
 * welcome screen (onboarding.ts) asking which ROLE this machine plays:
 *
 *   standalone  desktop app starts a local open hub+sessiond+agent; the viewer
 *               connects over loopback with no pin.
 *   hub         desktop app starts a local TRUST-mode hub (this viewer's device
 *               is auto-trusted); the viewer connects with its signer and pins
 *               the hub key, which is surfaced in the sidebar for spokes.
 *   spoke       join an existing hub: a small form collects the remote URL and
 *               hub-key pin. In the desktop app this also starts a local
 *               sessiond+agent so this Mac's shells join the fleet; in a plain
 *               browser the viewer simply connects (remote/spoke use).
 *
 * The choice persists under localStorage 'glass.role' and is reconfigurable at
 * any time via the app's File menu (Tauri 'glass://reconfigure' event) or the
 * sidebar gear — both stop the backend, clear the role, and re-run onboarding.
 * The device identity itself is generated by auth.ts and kept in localStorage.
 * For local development, a `?hub=` query param still connects straight to that
 * hub without touching the stored role.
 */
